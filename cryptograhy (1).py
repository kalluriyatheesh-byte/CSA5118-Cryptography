def dec(a, b, m):
    r1, c1, r2, c2 = None, None, None, None
    for i in range(5):
        for j in range(5):
            if m[i][j] == a:
                r1, c1 = i, j
            if m[i][j] == b:
                r2, c2 = i, j
    if r1 is None or r2 is None:
        return a + b

    if r1 == r2:
        return m[r1][(c1 - 1) % 5] + m[r2][(c2 - 1) % 5]
    if c1 == c2:
        return m[(r1 - 1) % 5][c1] + m[(r2 - 1) % 5][c2]
    return m[r1][c2] + m[r2][c1]

